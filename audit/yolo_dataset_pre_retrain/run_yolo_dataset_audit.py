def rel(path: str) -> str:
    return os.path.relpath(path, ROOT).replace("\\", "/")


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def ahash64(bgr: np.ndarray) -> int:
    gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
    small = cv2.resize(gray, (8, 8), interpolation=cv2.INTER_AREA)
    bits = (small > small.mean()).flatten()
    value = 0
    for bit in bits:
        value = (value << 1) | int(bool(bit))
    return value


def hamming(a: int, b: int) -> int:
    return (a ^ b).bit_count()


def classify_source(path: str, stem: str) -> str:
    p = path.replace("\\", "/").lower()
    s = stem.lower()
    if "blank_skin" in s or "dummy_test" in s:
        return "synthetic"
    if "synthetic_wound" in p or s.startswith("syn_wound") or s.startswith("synthetic_wound"):
        return "synthetic"
    if "injury_dataset" in p or s.startswith("sample_"):
        return "synthetic"
    if "public_wound" in p or s.startswith("public_sample"):
        # Generated by download_public_datasets.py despite the folder name.
        return "synthetic"
    if "yolo_real_wound" in p:
        return "synthetic"
    return "unknown"


def load_yaml_names(yaml_path: str) -> dict[int, str]:
    names: dict[int, str] = {}
    if not os.path.exists(yaml_path):
        return names
    with open(yaml_path, encoding="utf-8") as handle:
        in_names = False
        for line in handle:
            stripped = line.strip()
            if stripped.startswith("names:"):
                in_names = True
                continue
            if in_names:
                if not stripped or (":" in stripped and not stripped[0].isdigit() and not stripped.startswith("'") and not stripped.startswith('"')):
                    if stripped.startswith("path:") or stripped.startswith("train:") or stripped.startswith("val:") or stripped.startswith("test:"):
                        break
                if ":" in stripped:
                    key, val = stripped.split(":", 1)
                    key = key.strip()
                    if key.isdigit():
                        names[int(key)] = val.strip().strip("'\"")
    return names


def parse_label_file(label_path: str, names: dict[int, str], img_w: int, img_h: int) -> dict:
    issues = []
    boxes = []
    if not os.path.exists(label_path):
        return {"missing": True, "empty": False, "boxes": [], "issues": [{"type": "missing_label", "path": rel(label_path)}]}
    with open(label_path, encoding="utf-8", errors="replace") as handle:
        raw_lines = handle.readlines()
    lines = [ln.strip() for ln in raw_lines]
    nonempty = [ln for ln in lines if ln]
    if not nonempty:
        return {"missing": False, "empty": True, "boxes": [], "issues": [{"type": "empty_label", "path": rel(label_path)}]}

    for idx, line in enumerate(nonempty, start=1):
        parts = line.split()
        if len(parts) != 5:
            issues.append({
                "type": "invalid_label",
                "reason": f"expected_5_fields_got_{len(parts)}",
                "line": idx,
                "path": rel(label_path),
                "text": line[:120],
            })
            continue
        try:
            cid = int(float(parts[0]))
            xc, yc, w, h = (float(parts[1]), float(parts[2]), float(parts[3]), float(parts[4]))
        except ValueError:
            issues.append({
                "type": "invalid_label",
                "reason": "non_numeric",
                "line": idx,
                "path": rel(label_path),
                "text": line[:120],
            })
            continue
        if cid not in names:
            issues.append({
                "type": "invalid_label",
                "reason": f"class_id_out_of_range:{cid}",
                "line": idx,
                "path": rel(label_path),
            })
        if any(not np.isfinite(v) for v in (xc, yc, w, h)):
            issues.append({
                "type": "invalid_label",
                "reason": "non_finite_coord",
                "line": idx,
                "path": rel(label_path),
            })
            continue
        x1 = xc - w / 2.0
        y1 = yc - h / 2.0
        x2 = xc + w / 2.0
        y2 = yc + h / 2.0
        if w <= EPS or h <= EPS:
            issues.append({
                "type": "zero_area_box",
                "line": idx,
                "path": rel(label_path),
                "w": w,
                "h": h,
            })
        outside = x1 < -EPS or y1 < -EPS or x2 > 1 + EPS or y2 > 1 + EPS
        if outside or xc < -EPS or xc > 1 + EPS or yc < -EPS or yc > 1 + EPS:
            issues.append({
                "type": "box_outside_image",
                "line": idx,
                "path": rel(label_path),
                "xywh": [xc, yc, w, h],
                "xyxy_norm": [x1, y1, x2, y2],
                "image_wh": [img_w, img_h],
            })
        class_name = names.get(cid, f"id_{cid}")
        boxes.append({
            "class_id": cid,
            "class_name": class_name,
            "xywh": [xc, yc, w, h],
        })
    return {"missing": False, "empty": False, "boxes": boxes, "issues": issues}


def iter_images(root: str):
    for dirpath, _, filenames in os.walk(root):
        for name in filenames:
            if os.path.splitext(name)[1].lower() in IMG_EXTS:
                yield os.path.join(dirpath, name)


def infer_split(path: str) -> str:
    parts = path.replace("\\", "/").lower().split("/")
    if "valid" in parts:
        return "val"
    for split in SPLITS:
        if split in parts:
            return split
    return "unsplit"


def load_manifest(path: str) -> list[dict]:
    if not os.path.exists(path):
        return []
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


class UnionFind:
    def __init__(self):
        self.parent = {}

    def add(self, x):
        self.parent.setdefault(x, x)

    def find(self, x):
        self.add(x)
        while self.parent[x] != x:
            self.parent[x] = self.parent[self.parent[x]]
            x = self.parent[x]
        return x

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.parent[rb] = ra

    def groups(self):
        buckets = defaultdict(list)
        for key in self.parent:
            buckets[self.find(key)].append(key)
        return [sorted(v) for v in buckets.values() if len(v) > 1]


def audit_yolo_dataset(dataset_id: str, root: str, names: dict[int, str], layout: str) -> dict:
    records = []
    issues = []
    if not os.path.exists(root):
        return {
            "dataset_id": dataset_id,
            "root": rel(root),
            "present": False,
            "error": "missing_directory",
        }

    image_paths = sorted(iter_images(root))
    label_files = []
    for dirpath, _, filenames in os.walk(root):
        if os.path.basename(dirpath).lower() in {"labels"} or "labels" in dirpath.replace("\\", "/").lower().split("/"):
            for name in filenames:
                if name.lower().endswith(".txt"):
                    label_files.append(os.path.join(dirpath, name))

    stem_to_images = defaultdict(list)
    for path in image_paths:
        stem = os.path.splitext(os.path.basename(path))[0]
        stem_to_images[stem].append(rel(path))

    byte_groups = defaultdict(list)
    pixel_groups = defaultdict(list)
    split_pixel = {s: set() for s in (*SPLITS, "unsplit")}
    split_stems = {s: set() for s in (*SPLITS, "unsplit")}
    split_files = Counter()
    boxes_by_split_class = defaultdict(Counter)
    images_by_split_class = defaultdict(Counter)
    source_counts = Counter()
    empty_labels = []
    missing_labels = []
    unreadable = []
    negatives = []
    per_image = []

    for path in image_paths:
        split = infer_split(path)
        stem = os.path.splitext(os.path.basename(path))[0]
        split_files[split] += 1
        split_stems[split].add(stem)
        source = classify_source(path, stem)
        source_counts[source] += 1

        with open(path, "rb") as handle:
            raw = handle.read()
        byte_hash = sha256_bytes(raw)
        byte_groups[byte_hash].append(rel(path))

        bgr = cv2.imdecode(np.frombuffer(raw, dtype=np.uint8), cv2.IMREAD_COLOR)
        if bgr is None:
            unreadable.append(rel(path))
            issues.append({"type": "unreadable_image", "path": rel(path)})
            continue
        h, w = bgr.shape[:2]
        pixel_hash = sha256_bytes(bgr.tobytes() + f"|{w}x{h}".encode())
        pixel_groups[pixel_hash].append(rel(path))
        split_pixel[split].add(pixel_hash)
        phash = ahash64(bgr)
        mean_std = float(bgr.std())

        label_path = None
        parent = os.path.dirname(path)
        candidates = [
            os.path.join(parent.replace(os.path.join("images", split), os.path.join("labels", split)), stem + ".txt") if split != "unsplit" else None,
            os.path.join(os.path.dirname(parent), "labels", split if split != "unsplit" else "", stem + ".txt"),
            os.path.join(root, "labels", split, stem + ".txt") if split != "unsplit" else None,
            os.path.join(os.path.dirname(parent), "labels", stem + ".txt"),
        ]
        # synthetic_wound layout: {split}/images + {split}/labels
        if os.path.basename(parent).lower() == "images":
            candidates.insert(0, os.path.join(os.path.dirname(parent), "labels", stem + ".txt"))
        for cand in candidates:
            if cand and os.path.isfile(cand):
                label_path = cand
                break
        parsed = parse_label_file(label_path, names, w, h) if label_path else {
            "missing": True, "empty": False, "boxes": [], "issues": [{"type": "missing_label", "path": rel(path)}]
        }
        issues.extend(parsed["issues"])
        if parsed["missing"]:
            missing_labels.append(rel(path))
        if parsed["empty"]:
            empty_labels.append(rel(label_path) if label_path else rel(path))
        if parsed["empty"] or (not parsed["missing"] and not parsed["boxes"]) or mean_std < 8.0:
            if parsed["empty"] or (not parsed["missing"] and not parsed["boxes"]) or "blank" in stem or "dummy" in stem:
                negatives.append({
                    "path": rel(path),
                    "split": split,
                    "empty_label": parsed["empty"] or parsed["missing"],
                    "pixel_std": round(mean_std, 3),
                    "reason": "empty_or_missing_label" if (parsed["empty"] or parsed["missing"] or not parsed["boxes"]) else "near_uniform_pixels",
                })

        present_classes = sorted({b["class_name"] for b in parsed["boxes"]})
        for cls in present_classes:
            images_by_split_class[split][cls] += 1
        for box in parsed["boxes"]:
            boxes_by_split_class[split][box["class_name"]] += 1

        rec = {
            "path": rel(path),
            "stem": stem,
            "split": split,
            "ext": os.path.splitext(path)[1].lower(),
            "width": w,
            "height": h,
            "byte_sha256": byte_hash,
            "pixel_sha256": pixel_hash,
            "ahash64": phash,
            "source_class": source,
            "label_path": rel(label_path) if label_path else None,
            "classes": present_classes,
            "n_boxes": len(parsed["boxes"]),
            "pixel_std": round(mean_std, 3),
        }
        records.append(rec)
        per_image.append(rec)

    # Labels with no image
    image_stems = set(stem_to_images)
    orphan_labels = []
    for lp in label_files:
        stem = os.path.splitext(os.path.basename(lp))[0]
        if stem not in image_stems:
            orphan_labels.append(rel(lp))
            issues.append({"type": "orphan_label", "path": rel(lp)})

    duplicate_byte = {k: v for k, v in byte_groups.items() if len(v) > 1}
    duplicate_pixel = {k: v for k, v in pixel_groups.items() if len(v) > 1}
    duplicate_stems = {k: v for k, v in stem_to_images.items() if len(v) > 1}

    jpg_png_pairs = []
    for stem, paths in stem_to_images.items():
        exts = {os.path.splitext(p)[1].lower() for p in paths}
        if {".jpg", ".png"} <= exts or {".jpeg", ".png"} <= exts:
            jpg_png_pairs.append({"stem": stem, "files": paths})

    # Cross-split leakage by pixel hash and stem
    leakage_pixel = []
    for a, b in (("train", "val"), ("train", "test"), ("val", "test")):
        overlap = split_pixel[a] & split_pixel[b]
        if overlap:
            leakage_pixel.append({
                "splits": [a, b],
                "shared_unique_images": len(overlap),
                "examples": [pixel_groups[h][:4] for h in list(overlap)[:MAX_LIST]],
            })
    leakage_stems = []
    for a, b in (("train", "val"), ("train", "test"), ("val", "test")):
        overlap = split_stems[a] & split_stems[b]
        if overlap:
            leakage_stems.append({"splits": [a, b], "shared_stems": sorted(overlap)[:MAX_LIST], "count": len(overlap)})

    # Near-identical clusters (ahash)
    uf = UnionFind()
    hashed = [(r["path"], r["ahash64"], r["split"]) for r in records]
    for i in range(len(hashed)):
        for j in range(i + 1, len(hashed)):
            if hamming(hashed[i][1], hashed[j][1]) <= AHASH_NEAR:
                uf.union(hashed[i][0], hashed[j][0])
    near_clusters = uf.groups()
    near_cross_split = []
    path_split = {r["path"]: r["split"] for r in records}
    for group in near_clusters:
        splits = sorted({path_split[p] for p in group})
        if len(splits) > 1:
            near_cross_split.append({"splits": splits, "size": len(group), "examples": group[:MAX_LIST]})

    unique_by_split = {}
    for split in (*SPLITS, "unsplit"):
        unique_by_split[split] = {
            "image_files": int(split_files[split]),
            "unique_stems": len(split_stems[split]),
            "unique_byte_sha256": len({r["byte_sha256"] for r in records if r["split"] == split}),
            "unique_pixel_sha256": len(split_pixel[split]),
            "boxes_per_class": dict(boxes_by_split_class[split]),
            "unique_images_containing_class": dict(images_by_split_class[split]),
        }

    box_totals = Counter()
    img_class_totals = Counter()
    for split in SPLITS:
        box_totals.update(boxes_by_split_class[split])
        img_class_totals.update(images_by_split_class[split])
    imbalance = {}
    if box_totals:
        mx, mn = max(box_totals.values()), min(box_totals.values()) or 1
        imbalance = {
            "boxes_per_class": dict(box_totals),
            "unique_images_containing_class": dict(img_class_totals),
            "box_ratio_max_over_min": round(mx / mn, 3) if mn else None,
            "dominant_class": max(box_totals, key=box_totals.get),
            "rarest_class": min(box_totals, key=box_totals.get),
        }

    source_kind = "synthetic"
    kinds = set(source_counts)
    if kinds == {"synthetic"}:
        source_kind = "synthetic"
    elif kinds <= {"public"}:
        source_kind = "public"
    elif kinds <= {"real"}:
        source_kind = "real"
    elif len(kinds) > 1:
        source_kind = "mixed"
    else:
        source_kind = next(iter(kinds)) if kinds else "unknown"

    issue_counts = Counter(i["type"] for i in issues)
    return {
        "dataset_id": dataset_id,
        "root": rel(root),
        "present": True,
        "layout": layout,
        "names": {str(k): v for k, v in names.items()},
        "source_classification": source_kind,
        "source_file_counts": dict(source_counts),
        "source_classification_note": (
            "Folder names like public_wound_dataset / yolo_real_wound are not trusted. "
            "Classification uses generation scripts, manifests, and filename stems. "
            "public_sample_* and yolo_real_wound images are PIL drawings from "
            "ml/training/download_public_datasets.py."
        ),
        "splits": unique_by_split,
        "totals": {
            "image_files": len(image_paths),
            "unique_stems": len(stem_to_images),
            "unique_byte_sha256": len(byte_groups),
            "unique_pixel_sha256": len(pixel_groups),
            "label_files": len(label_files),
            "boxes_per_class": dict(box_totals),
            "unique_images_containing_class": dict(img_class_totals),
        },
        "class_imbalance": imbalance,
        "duplicate_jpg_png_pairs": jpg_png_pairs[:MAX_LIST],
        "duplicate_jpg_png_pair_count": len(jpg_png_pairs),
        "duplicate_byte_sha256_groups": len(duplicate_byte),
        "duplicate_pixel_sha256_groups": len(duplicate_pixel),
        "duplicate_byte_examples": list(duplicate_byte.values())[:MAX_LIST],
        "duplicate_pixel_examples": list(duplicate_pixel.values())[:MAX_LIST],
        "duplicate_stems": {k: v for k, v in list(duplicate_stems.items())[:MAX_LIST]},
        "duplicate_stem_count": len(duplicate_stems),
        "invalid_labels": [i for i in issues if i["type"] == "invalid_label"][:MAX_LIST],
        "invalid_label_count": issue_counts["invalid_label"],
        "empty_labels": empty_labels[:MAX_LIST],
        "empty_label_count": len(empty_labels),
        "missing_label_count": len(missing_labels),
        "missing_label_examples": missing_labels[:MAX_LIST],
        "boxes_outside_image": [i for i in issues if i["type"] == "box_outside_image"][:MAX_LIST],
        "boxes_outside_image_count": issue_counts["box_outside_image"],
        "zero_area_boxes": [i for i in issues if i["type"] == "zero_area_box"][:MAX_LIST],
        "zero_area_box_count": issue_counts["zero_area_box"],
        "orphan_label_count": len(orphan_labels),
        "orphan_label_examples": orphan_labels[:MAX_LIST],
        "unreadable_image_count": len(unreadable),
        "negative_or_no_injury": {
            "count": len(negatives),
            "examples": negatives[:MAX_LIST],
            "note": "Empty/missing YOLO labels, blank_skin/dummy_test, or near-uniform pixels.",
        },
        "train_val_test_leakage": {
            "exact_pixel_hash_across_splits": leakage_pixel,
            "exact_stem_across_splits": leakage_stems,
            "near_identical_ahash_hamming_le_6_across_splits": near_cross_split[:MAX_LIST],
            "near_identical_cluster_count": len(near_clusters),
            "near_identical_cross_split_cluster_count": len(near_cross_split),
        },
        "issue_counts": dict(issue_counts),
        "_records": records,
    }


def audit_subjects(manifest_path: str) -> dict:
    rows = load_manifest(manifest_path)
    if not rows:
        return {"present": False, "path": rel(manifest_path) if os.path.exists(manifest_path) else manifest_path}
    by_subj = defaultdict(set)
    remap = []
    for row in rows:
        subj = row.get("subject_id") or row.get("subject") or ""
        split = (row.get("split") or "").replace("valid", "val")
        if subj:
            by_subj[subj].add(split)
        raw = (row.get("raw_class") or row.get("class") or "").strip().lower()
        final = (row.get("final_class") or "").strip().lower()
        if raw and final and raw != final:
            remap.append({
                "sample_id": row.get("sample_id"),
                "subject_id": subj,
                "split": split,
                "raw_class": raw,
                "final_class": final,
            })
    leaked = {s: sorted(v) for s, v in by_subj.items() if len(v) > 1}
    return {
        "present": True,
        "path": rel(manifest_path),
        "rows": len(rows),
        "unique_subjects": len(by_subj),
        "subjects_in_multiple_splits": leaked,
        "subjects_in_multiple_splits_count": len(leaked),
        "raw_to_final_class_remaps": remap[:200],
        "raw_to_final_class_remap_count": len(remap),
        "raw_to_final_counts": dict(Counter(f"{r['raw_class']}->{r['final_class']}" for r in remap)),
    }


def md_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(lines)


